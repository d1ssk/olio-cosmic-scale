export const SPEED_OF_LIGHT_METERS_PER_SECOND = 299_792_458;
export const JULIAN_YEAR_SECONDS = 365.25 * 86_400;
export const AU_METERS = 149_597_870_700;
export const LIGHT_YEAR_METERS = SPEED_OF_LIGHT_METERS_PER_SECOND * JULIAN_YEAR_SECONDS;
export const PARSEC_METERS = (648_000 / Math.PI) * AU_METERS;

export const KILOPARSEC_METERS = 1_000 * PARSEC_METERS;
export const MEGAPARSEC_METERS = 1_000_000 * PARSEC_METERS;
export const GIGAPARSEC_METERS = 1_000_000_000 * PARSEC_METERS;
